// 화면 주소 → 설명서 키. 상세 주소(/groups/g1, /workflows/w1)는 앞부분으로 찾는다.
export function manualKeyFor(pathname) {
  if (MANUALS[pathname]) return pathname;
  if (pathname.startsWith('/groups')) return '/groups';
  if (pathname.startsWith('/workflows')) return '/editor';
  return '/';
}
